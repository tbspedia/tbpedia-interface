const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const source = fs.readFileSync(path.join(__dirname, 'src', 'main.js'), 'utf8');
new vm.Script(source, { filename: 'src/main.js' });
const banner = '/* Generated by node build.cjs from src/main.js. Do not edit directly. */\n';
fs.writeFileSync(path.join(__dirname, 'main.js'), banner + source);
console.log('Built main.js from src/main.js.');
